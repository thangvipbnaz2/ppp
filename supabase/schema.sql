-- ============================================================
-- Hàm reset sequence sau khi migrate id tường minh
-- ============================================================
create or replace function public.reset_products_id_seq()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  seq_name text;
begin
  seq_name := pg_get_serial_sequence('public.products', 'id');
  if seq_name is not null then
    execute format(
      'select setval(%L, coalesce((select max(id) from public.products), 0) + 1, false)',
      seq_name
    );
  end if;
end;
$$;

-- ============================================================
-- Hàm import/ cập nhật giá hàng loạt (chỉ service_role được gọi)
-- ============================================================
create or replace function public.import_product_prices(rows jsonb)
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  updated_count integer := 0;
begin
  for item in select * from jsonb_array_elements(rows)
  loop
    update public.products set
      price_no_vat = nullif(item->>'price_no_vat', '')::bigint,
      price_with_vat = nullif(item->>'price_with_vat', '')::bigint,
      retail_price = nullif(item->>'retail_price', '')::bigint,
      regular_price = nullif(item->>'regular_price', '')::bigint,
      vat_rate = coalesce(nullif(item->>'vat_rate', '')::numeric, vat_rate),
      price_status = coalesce(item->>'price_status', price_status),
      stock_status = coalesce(item->>'stock_status', stock_status),
      category_id = coalesce(nullif(item->>'category_id', '')::integer, category_id),
      brand = coalesce(item->>'brand', brand),
      image = coalesce(item->>'image', image),
      updated_at = now()
    where id = nullif(item->>'id', '')::integer;

    if found then
      updated_count := updated_count + 1;
    end if;
  end loop;

  return updated_count;
end;
$$;

revoke all on function public.import_product_prices(jsonb) from public, anon, authenticated;
grant execute on function public.import_product_prices(jsonb) to service_role;

