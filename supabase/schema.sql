-- 1. Bảng danh mục (17 nhóm sản phẩm)
create table if not exists public.categories (
  id integer generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text,
  icon text,
  image text,
  parent_id integer references public.categories(id) on delete set null,
  sort_order integer not null default 0,
  created_at timestamptz not null default now()
);

-- 2. Bảng sản phẩm
create table if not exists public.products (
  id integer generated by default as identity primary key,
  name text not null,
  slug text not null unique,
  sku text,
  category_id integer references public.categories(id) on delete set null,
  category_original text,
  brand text,
  price_no_vat bigint,
  price_with_vat bigint,
  retail_price bigint,
  regular_price bigint,
  vat_rate numeric(5, 4) not null default 0.08,
  price_status text not null default 'available' check (price_status in ('available', 'contact')),
  stock_status text not null default 'instock' check (stock_status in ('instock', 'outofstock')),
  support_amount bigint,
  support_mechanism text,
  gift_support text,
  image text,
  images jsonb not null default '[]'::jsonb,
  installation_images jsonb not null default '[]'::jsonb,
  highlights jsonb not null default '[]'::jsonb,
  applications jsonb not null default '[]'::jsonb,
  specs jsonb not null default '{}'::jsonb,
  specs_table jsonb not null default '[]'::jsonb,
  attributes jsonb not null default '[]'::jsonb,
  short_description text,
  description text,
  source text,
  is_active boolean not null default true,
  is_featured boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists products_category_id_idx on public.products(category_id);
create index if not exists products_is_active_idx on public.products(is_active);
create index if not exists products_name_idx on public.products(name);

-- 3. Đơn hàng
create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  order_code text not null unique,
  customer_name text not null,
  customer_phone text not null,
  customer_address text not null,
  customer_note text,
  payment_method text not null check (payment_method in ('cod', 'bank_transfer')),
  subtotal bigint not null default 0,
  shipping_fee bigint not null default 0,
  discount bigint not null default 0,
  total bigint not null default 0,
  status text not null default 'new' check (status in ('new', 'confirmed', 'shipping', 'completed', 'cancelled')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists orders_phone_idx on public.orders(customer_phone);
create index if not exists orders_status_idx on public.orders(status);
create index if not exists orders_created_at_idx on public.orders(created_at desc);

-- 4. Chi tiết đơn hàng
create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  product_id integer references public.products(id) on delete set null,
  product_name text not null,
  product_image text,
  quantity integer not null check (quantity > 0),
  unit_price bigint not null,
  total_price bigint not null,
  created_at timestamptz not null default now()
);

create index if not exists order_items_order_id_idx on public.order_items(order_id);

